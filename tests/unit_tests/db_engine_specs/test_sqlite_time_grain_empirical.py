"""Empirical regression tests for SQLite time-grain SQL expressions.

Each expected value was obtained by executing Superset's actual SQL from
``SqliteEngineSpec._time_grain_expressions`` against a real SQLite database.
The timestamp battery stresses bucket boundaries: Sunday/Monday adjacency,
month/quarter/year transitions, Feb 29 leap year, and ordinary datetimes
spanning multiple years.

Reference convention: ISO-8601 (week starts Monday).

Findings:
- WEEK grain uses Sunday-start (SQLite strftime %w convention), diverging
  from the ISO-8601 Monday-start reference. This is a legitimate dialect
  convention, not a defect.
- Redundancies: THIRTY_MINUTES == HALF_HOUR, WEEK == WEEK_STARTING_SUNDAY,
  QUARTER == QUARTER_YEAR (identical SQL and identical output across all
  boundary timestamps).
"""

